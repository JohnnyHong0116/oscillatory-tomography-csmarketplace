"""Regenerate genuine Python-computed web previews; never fabricate plot values.

Run from the repository root with the project Python environment. The original
MATLAB acquisition/configuration is preserved in the full forward case. The
quick recovery explicitly changes resolution and acquisition for interactive use.
Reference truth is generated by MATLAB; all preview outputs are recomputed by Python.
"""
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import argparse

from oscillatory_tomography.api import AnalyzeRequest, analyze

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "web/src/data"
SOURCE = "https://github.com/wischydro-cardiff/oscillatory-tomography/blob/7aa7146ec4d7dce63f0a4a6922ed458d6df56d5f/testing_inversion_3D_geostat.m"


def request_for(config, mode):
    keys = AnalyzeRequest.model_fields.keys()
    payload = {k: v for k, v in config.items() if k in keys}
    payload["analysisMode"] = mode
    payload["wells"] = [{k: w[k] for k in ("id", "name", "x", "y", "z")} for w in config["wells"]]
    payload["tests"] = [{k: v for k, v in t.items() if k != "status"} for t in config["tests"]]
    return AnalyzeRequest.model_validate(payload)


def generate(kind):
    quick = kind == "quick"
    config = json.loads((DATA / ("matlab3dQuickConfig.json" if quick else "matlab3dConfig.json")).read_text())
    mode = "synthetic_demo" if quick else "forward"
    result = analyze(request_for(config, mode), progress=lambda stage, percent, test, message: print(f"{percent}% {message}", flush=True))
    # Hash the relevant Python source so the snapshot's computation is traceable
    # even before the current working tree has been committed.
    digest = hashlib.sha256()
    for file in sorted((ROOT / "src/oscillatory_tomography").glob("*.py")):
        digest.update(file.name.encode()); digest.update(file.read_bytes())
    preview = dict(config=config, result=result, provenance=dict(
        generatedAt=datetime.now(timezone.utc).isoformat(), solver="Python transcription",
        source=SOURCE, sourceTreeSha256=digest.hexdigest(),
        note="Reduced 8³-cell, central-pump / 14-observer, four-period recovery; not the full MATLAB baseline." if quick else "Original MATLAB geometry, mesh, acquisition and field statistics; Python forward result, not MATLAB output or a full inversion.",
        randomNote="Uses the MATLAB-generated legacy seed-0 reference truth on the matching mesh; outputs are computed by Python."))
    output = DATA / ("matlab3dQuickPreview.json" if quick else "matlab3dPreview.json")
    output.write_text(json.dumps(preview, separators=(",", ":"), allow_nan=False) + "\n", encoding="utf-8")
    print(f"Saved {output.name}: {len(result['pairs'])} responses, {result['runtimeSeconds']:.2f}s", flush=True)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--case", choices=["full", "quick", "both"], default="both")
    args = parser.parse_args()
    for kind in (["full", "quick"] if args.case == "both" else [args.case]):
        generate(kind)
